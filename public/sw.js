// Minimal offline cache: no build-time asset manifest (Vite's JS/CSS filenames
// are content-hashed and change every build), so instead of precaching a fixed
// list, same-origin GET requests are cached as they're made and served from
// cache first, with the network response refreshing the cache in the background.
// Cross-origin requests (Google Fonts) are left to the browser/network as-is.
const CACHE_NAME = 'checklist-collection-v1';

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request)
        .then((response) => {
          if (response && response.ok) {
            var copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
